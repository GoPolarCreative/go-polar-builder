export class ProductNotOnStoreError extends Error {
  constructor(
    readonly key: PriceKey,
    readonly proposedRef: string,
  ) {
    const product = PRICING[key]
    super(
      `"${product.label}" does not exist on the Shopify store, so no checkout can be built for it. Create it with the SKU "${proposedRef}". ${
        product.store.todo ?? ''
      } Then set ${variantEnvKey(proposedRef)}. See SHOPIFY-SETUP.md. Until then: ${
        product.store.breaks ?? 'this path cannot complete.'
      }`,
    )
    this.name = 'ProductNotOnStoreError'
  }
}

export class PriceUnresolvedError extends Error {
  constructor(readonly key: PriceKey) {
    const product = PRICING[key]
    super(
      `"${product.label}" has no settled price, so it cannot be sold and no number may be shown. See SHOPIFY-SETUP.md.`,
    )
    this.name = 'PriceUnresolvedError'
  }
}

/**
 * The identifier to sell by, or a loud refusal. The only way a product reference reaches a
 * checkout, so neither a missing product nor an unsettled price can quietly become a broken cart.
 *
 * Being in draft is NOT checked here: the store is the authority on that and it is checked live
 * against the Admin API, so publishing a product takes effect immediately without a code change.
 */
export function checkoutRef(key: PriceKey): string {
  const product = PRICING[key]
  if (!product.ref) throw new ProductNotOnStoreError(key, product.proposedRef)
  if (product.incGstCents === null) throw new PriceUnresolvedError(key)
  return product.ref
}

export function kindForRef(ref: string): OrderKind | null {
  for (const product of Object.values(PRICING)) {
    if (product.ref === ref) return product.kind
    // A proposed ref matches too: if a product is created before this file is updated, an order
    // for it should still be understood rather than dropped on the floor.
    if (product.proposedRef === ref) return product.kind
  }
  return null
}

export function productForRef(ref: string): { key: PriceKey; product: Product } | null {
  for (const [key, product] of Object.entries(PRICING) as Array<[PriceKey, Product]>) {
    if (product.ref === ref || product.proposedRef === ref) return { key, product }
  }
  return null
}

export function knownRefs(): string[] {
  return Object.values(PRICING).flatMap((p) => (p.ref ? [p.ref, p.proposedRef] : [p.proposedRef]))
}

/**
 * Shopify variant and selling-plan ids, one env var per product, named from its ref:
 *
 *   SHOPIFY_VARIANT_BUILD_TOKEN=62852208328863
 *   SHOPIFY_SELLING_PLAN_WEBSITE_HOSTING_AUSTRALIA=6890123456
 *
 * Where a verified variant id is already recorded above, the env var is an override rather than a
 * requirement, so a different store can be pointed at without a code change.
 */
export function variantEnvKey(ref: string): string {
  return `SHOPIFY_VARIANT_${ref.replace(/-/g, '_').toUpperCase()}`
}

export function sellingPlanEnvKey(ref: string): string {
  return `SHOPIFY_SELLING_PLAN_${ref.replace(/-/g, '_').toUpperCase()}`
}

/** Env var first, then the id verified from the store. Null when neither is known. */
export function variantIdFor(ref: string, env: Record<string, string | undefined>): string | null {
  const fromEnv = env[variantEnvKey(ref)]?.trim()
  if (fromEnv) return fromEnv
  return productForRef(ref)?.product.variantId ?? null
}

