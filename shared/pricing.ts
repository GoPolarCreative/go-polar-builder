/**
 * Every product, price and Shopify identifier in the business, in one place.
 *
 * PRICES ARE GST-INCLUSIVE, because the store is. `taxesIncluded: true`, verified on
 * itscold.com.au. The app displays the number the customer is actually charged, labelled
 * "inc GST", because advertising "$30 + GST" and then landing a tradie on a $33.00 checkout reads
 * as a bait and switch. One number, the real one, everywhere. See DECISIONS.md D31.
 *
 * HOW A PRODUCT IS IDENTIFIED, and why it is not always the handle.
 *
 * The three subscription products are identified by their Shopify **handle**, which is known and
 * stable. The three one-off products created on 2026-08-19 are identified by their **SKU**, which
 * was set deliberately to a known value, while their handles were auto-generated by Shopify from
 * titles nobody here chose ("DIY Website Build" and so on). Guessing a handle from a title is
 * exactly the sort of assumption that produces a checkout link that 404s, so this file records
 * which kind of identifier each product actually has and uses that. See DECISIONS.md D35.
 *
 * THE RULES THAT REMAIN NON-NEGOTIABLE.
 *
 * 1. NO INVENTED IDENTIFIERS. A product that does not exist has `ref: null`, and a checkout for it
 *    throws by name saying what to create.
 * 2. NO INVENTED PRICES. `extra-edits` has never been priced, so nothing shows a number for it.
 * 3. SELLING PLANS ARE NOT OPTIONAL. All three subscriptions have `requiresSellingPlan: true`, so
 *    Shopify REJECTS a line without a plan id. A missing plan id is fatal, not a downgrade.
 * 4. THE STORE IS THE AUTHORITY ON WHETHER SOMETHING CAN BE SOLD. All six products are published
 *    and active as of 2026-08-19, but this file is not what decides that: `checkStoreProducts` in
 *    server/lib/shopify.ts asks Shopify immediately before every checkout, so a product being
 *    unpublished, archived or re-priced is caught without anybody having to remember to edit here.
 */

export type PriceKey =
  | 'build'
  | 'additionalPage'
  | 'hosting'
  | 'domain'
  | 'email'
  | 'postLiveEdit'
  | 'extraEdits'
  | 'discharge'

export type OrderKind = 'build' | 'page' | 'hosting' | 'domain' | 'email' | 'edit' | 'discharge'

/** Australian GST. Used only to convert between the two ways of stating the same price. */
export const GST_RATE = 0.1

export interface Product {
  /**
   * The stable identifier this app sells by. NULL MEANS THE PRODUCT DOES NOT EXIST on the store,
   * and nothing may treat that as licence to guess one.
   */
  ref: string | null
  /** Which kind of Shopify identifier `ref` is. Handles and SKUs are not interchangeable. */
  refKind: 'handle' | 'sku'
  /** What `ref` will be once the product is created. Documentation for SHOPIFY-SETUP.md. */
  proposedRef: string
  label: string
  /** What the customer is charged, GST included, in whole cents. null means no price may be shown. */
  incGstCents: number | null
  recurrence: 'once' | 'monthly'
  kind: OrderKind
  /** True where the store sets requiresSellingPlan. Such a line is refused without a plan id. */
  requiresSellingPlan: boolean
  /** Verified numeric variant id, where it is known. An env var of the same name overrides it. */
  variantId: string | null
  /** Verified numeric product id. How SKU-identified products are looked up on the store. */
  productId: string | null
  /**
   * The product's real Shopify handle, for reference only.
   *
   * NOTHING SELLS BY THIS for a SKU-identified product. It is recorded because it is now known and
   * because somebody looking at a Shopify URL should be able to find the product here, but the app
   * matches on variant id and SKU. A handle changes when somebody edits a title; a SKU does not.
   */
  storeHandle: string | null
  store: StoreState
}

export interface StoreState {
  exists: boolean
  title?: string
  /**
   * Created but not published. A draft product cannot be bought by anybody, so this blocks the
   * same way a missing product does. Nothing sets it today: all six are published. Kept because
   * the next product created will start life in draft too.
   */
  draft?: boolean
  sellingPlan?: { group: string; plan: string; interval: 'MONTH' | 'YEAR'; intervalCount: number }
  /** What is left to do, in Chris's terms. Rendered into SHOPIFY-SETUP.md. */
  todo?: string
  /** What breaks in this app until it is done. */
  breaks?: string
}

